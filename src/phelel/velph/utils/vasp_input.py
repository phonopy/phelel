"""Writers and readers of the VASP input files INCAR, KPOINTS and POTCAR."""

from __future__ import annotations

import io
import os
from collections import defaultdict
from collections.abc import Mapping, Sequence
from typing import Any

import numpy as np

from phelel.velph.config.schema import KpointsMesh, LinePath


def write_incar(filename: str | os.PathLike, incar: Mapping[str, Any]) -> None:
    """Write INCAR.

    The tag names are written in upper case and in alphabetical order.  True
    and False are written as .TRUE. and .FALSE., and a list as its values
    separated by spaces.  MAGMOM is written in the form n*value, such as
    3*1.0 3*-1.0.  A tag whose value is None is not written.

    """
    _write_lines(filename, _incar_lines(incar))


def write_kpoints_mesh(filename: str | os.PathLike, kpoints: KpointsMesh) -> None:
    """Write KPOINTS of a mesh.

    A mesh of three integers is written as a Gamma-centred mesh.  The grid
    matrix of a generalized regular grid is written by its generating vectors
    in the basis of the reciprocal basis vectors.  The shift is that of
    kpoints, or zero.

    """
    shift = kpoints.shift if kpoints.shift is not None else (0, 0, 0)
    lines = ["# Generated by velph", "0"]
    if np.ndim(kpoints.mesh) == 1:
        lines.append("Gamma")
        lines.append(" ".join([f"{v:13d}" for v in kpoints.mesh]))  # type: ignore[union-attr]
    else:
        lines.append("Reciprocal")
        mesh_inv_t = np.linalg.inv(kpoints.mesh).T
        mesh_inv_t = np.where(np.abs(mesh_inv_t) < 1e-15, 0, mesh_inv_t)
        for vec in mesh_inv_t:
            lines.append(" ".join([f"{v:20.16f}" for v in vec]))
    lines.append(" ".join([f"{v:20.16f}" for v in shift]))
    _write_lines(filename, lines)


def write_kpoints_line(filename: str | os.PathLike, kpoints: LinePath) -> None:
    """Write KPOINTS of a band path in line mode.

    kpoints has to give the path, and its labels are written when it gives
    them.

    """
    assert kpoints.path is not None
    lines = [
        "k points along high symmetry lines by velph",
        str(kpoints.line),
        "line mode",
        "fractional",
    ]
    for i_segment, segment in enumerate(kpoints.path):
        for i in range(2):
            coord = " ".join([f"{x:.8f}" for x in segment[i]])
            if kpoints.label is not None:
                lines.append(f"{coord} {kpoints.label[i_segment][i]}")
            else:
                lines.append(coord)
        lines.append("")
    _write_lines(filename, lines)


class VaspPotcar:
    """POTCAR reader.

    Attributes
    ----------
    enmax : list[float]
        ENMAX of atoms.

    """

    value_types = {"ENMAX": float, "TITEL": str}

    def __init__(self, fp: str | os.PathLike | io.TextIOBase):
        """Init method.

        fp : str, os.PathLike, or typing.IO
            typing.IO is file-like object, e.g., io.StringIO or file object
            obtained by open(). Otherwise, file path.

        """
        self._property_dict: defaultdict[str, list] = defaultdict(list)
        self._read(fp)

    @property
    def enmax(self) -> list[float]:
        """Return values of ENMAX in POTCAR as a list."""
        return self._property_dict["ENMAX"]

    @property
    def titel(self) -> list[str]:
        """Return values of TITEL in POTCAR as a list."""
        return self._property_dict["TITEL"]

    def _read(self, fp: str | os.PathLike | io.TextIOBase):
        if isinstance(fp, io.TextIOBase):
            self._parse(fp)
        else:
            with open(fp) as _fp:
                self._parse(_fp)

    def _parse(self, fp: io.TextIOBase):
        """Parse lines of POTCAR.

        This method will be more complicated to support more properties.

        """
        for line in fp:
            for key in self.value_types:
                if key in line:
                    if key == "ENMAX":
                        ary = line.split()
                        index = ary.index(key)
                        valstr = ary[index + 2].strip(" ;")
                        value = self.value_types[key](valstr)
                        self._property_dict[key].append(value)
                    elif key == "TITEL":
                        ary = line.split("=")
                        self._property_dict[key].append(ary[1].strip())


def _write_lines(filename: str | os.PathLike, lines: Sequence[str]) -> None:
    with open(filename, "w") as w:
        print("\n".join(lines), file=w)


def _incar_lines(incar: Mapping[str, Any]) -> list[str]:
    lines = []
    for key, value in sorted(incar.items(), key=lambda pair: pair[0].lower()):
        if value is None:
            continue
        tag = key.upper()
        if isinstance(value, bool):
            lines.append(f"{tag} = {'.TRUE.' if value else '.FALSE.'}")
        elif isinstance(value, list):
            values = _flatten(value)
            if key == "magmom":
                lines.append(f"{tag} = {_compress_magmom_values(values)}")
            else:
                lines.append(f"{tag} = {' '.join(f'{v}' for v in values)}")
        elif isinstance(value, (str, float, int)):
            lines.append(f"{tag} = {value}")
        else:
            raise NotImplementedError(
                f"Handler for value type {type(value)} not implemented."
            )
    return lines


def _compress_magmom_values(values: Sequence[float], tolerance: float = 1e-15) -> str:
    groups = [[values[0]]]
    for i, v in enumerate(values[1:]):
        if abs(v - values[i]) < tolerance:
            groups[-1].append(v)
        else:
            groups.append([v])
    return " ".join([f"{len(group)}*{group[0]}" for group in groups])


def _flatten(values: Sequence[Any]) -> list[Any]:
    flat = []
    for v in values:
        if isinstance(v, list):
            flat += _flatten(v)
        else:
            flat.append(v)
    return flat
